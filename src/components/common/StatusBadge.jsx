import { AlertTriangle, CircleDot, ShieldCheck } from 'lucide-react'
import {
  getCategoryMeta,
  getSeverityMeta,
  getStatusMeta,
} from '../../utils/status'
import { Badge } from './Badge'

export function StatusBadge({ status, className }) {
  const meta = getStatusMeta(status)
  return (
    <Badge tone={meta.tone} dot className={className}>
      {meta.label}
    </Badge>
  )
}

export function SeverityBadge({ severity, className, showIcon = true }) {
  const meta = getSeverityMeta(severity)
  return (
    <Badge tone={meta.tone} className={className} icon={showIcon ? CircleDot : undefined}>
      {meta.label}
    </Badge>
  )
}

export function CategoryBadge({ category, className }) {
  const meta = getCategoryMeta(category)
  return (
    <Badge tone={meta.tone} className={className}>
      {meta.label}
    </Badge>
  )
}

export function HumanApprovedBadge({ className }) {
  return (
    <Badge tone="approved" icon={ShieldCheck} className={className}>
      Human approved
    </Badge>
  )
}

export function AiLabel({ className }) {
  return (
    <span
      className={`badge tone-violet ${className ?? ''}`}
      title="Generated by the demo rules engine, not an external AI service"
    >
      <AlertTriangle className="h-3 w-3" aria-hidden="true" />
      AI suggestion
    </span>
  )
}
